//! Name reservation for **tulpa**, the legend and memorial layer.
//!
//! A tulpa is what memory makes of history: legends, memorials, epithets, and
//! the manifestations of the dead. Its substance is attention — a tulpa's
//! presence scales with how often it is retold, and a legend nobody tells
//! fades.
//!
//! The boundaries are the point, and they mirror `fili`'s:
//!
//! - **Not ordinary event history.** That is `codicil`, the append-only log of
//!   what actually happened. A tulpa is a *view* over such a log, holding the
//!   retold subset.
//! - **Not descent.** That is `fili`, which records continuity of line across
//!   worlds. Where `fili` tracks who carried the line, `tulpa` holds what is
//!   remembered when nobody did.
//!
//! Named from Tibetan *sprul-pa* by way of two westernizations, and chosen to
//! complete a triad the stack already held: **servitor** (created and bounded)
//! → **tulpa** (remembered and autonomous) → **egregore** (collective and
//! emergent).
//!
//! No implementation yet.

